// 额外放行的字符：默认只有空白。
// 如果你希望某些字符不算「非法」（例如数字、英文字母、标点），
// 直接往下面这个字符串里加即可，不用改其它逻辑。
var EXTRA_ALLOWED_CHARS = '';

// 站名里出现过的所有字符 + 额外放行字符
var LEGAL_CHARS = (function () {
  var set = new Set();
  for (var i = 0; i < STATIONS.length; i++) {
    var name = STATIONS[i];
    for (var j = 0; j < name.length; j++) set.add(name[j]);
  }
  for (var k = 0; k < EXTRA_ALLOWED_CHARS.length; k++) set.add(EXTRA_ALLOWED_CHARS[k]);
  return set;
})();

/**
 * 文本里是否含有深圳地铁站名中不存在的字符。
 * @param {string} text
 * @returns {boolean}
 */
function containsIllegalChars(text) {
  if (text === null || text === undefined) return false;
  var s = String(text);
  for (var i = 0; i < s.length; i++) {
    var ch = s[i];
    if (/\s/.test(ch)) continue;          // 空白放行
    if (!LEGAL_CHARS.has(ch)) return true; // 站名里没这个字 → 非法
  }
  return false;
}
